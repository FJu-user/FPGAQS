`timescale 1 ns / 100 fs

// Dedicated CEA-861 1080p60 display PLL.
//
// The camera/system PLL is intentionally kept separate from this PLL.  This
// prevents a future 720p60/1080p60 display-mode change from disturbing the
// SC500CS MCLK, I2C configuration, MIPI receive path, ISP, or DDR controller.
// A later dual-mode clock manager can replace this static instance and keep
// the same pixel_clk/serial_clk/lock interface.
//
// 50 MHz / 3 * (89 + 0.1) = 1485 MHz VCO
// 1485 MHz / 10        = 148.5 MHz pixel clock
// 1485 MHz / 2         = 742.5 MHz TMDS serializer clock
module hdmi_pll_1080p60 (
    input  wire refclk,
    input  wire reset,
    output wire pixel_clk,
    output wire serial_clk,
    output wire lock
);

    // These feedback and loop-filter values are taken from the PLL instance
    // previously generated by TD for the same 1485 MHz VCO.  Only the output
    // dividers differ: /10 and /2 instead of /20 and /4.
    // round(0.1 * 2^28) = 26843546.
    localparam integer HDMI_PLL_FRAC_0P1 = 28'd26843546;

    wire [6:0] clkc;

    assign pixel_clk  = clkc[0];
    assign serial_clk = clkc[1];

    PH1P_PHY_PLL_V2 #(
        .FIN                    ("50.000000000"),
        .PLL_FEED_TYPE          ("INTERNAL"),
        .FEEDBK_MODE            ("NOCOMP"),
        .FBKCLK                 ("VCO_PHASE0"),
        .FBKCLK_INT             ("VCO_PHASE0"),
        .REFCLK_DIV             (3),
        .FBCLK_DIV              (89),

        .CLKC0_ENABLE           ("ENABLE"),
        .CLKC1_ENABLE           ("ENABLE"),
        .CLKC2_ENABLE           ("DISABLE"),
        .CLKC3_ENABLE           ("DISABLE"),
        .CLKC4_ENABLE           ("DISABLE"),
        .CLKC5_ENABLE           ("DISABLE"),
        .CLKC6_ENABLE           ("DISABLE"),

        .PREDIV_MUXC0           ("VCO"),
        .PREDIV_MUXC1           ("VCO"),
        .DIVOUT_MUXC0           ("DIV"),
        .DIVOUT_MUXC1           ("DIV"),
        .CLKC0_DIV              (10),
        .CLKC1_DIV              (2),
        .CLKC0_CPHASE           (9),
        .CLKC1_CPHASE           (1),
        .CLKC0_FPHASE           (0),
        .CLKC1_FPHASE           (0),
        .CLKC0_FPHASE_RSTSEL    (0),
        .CLKC1_FPHASE_RSTSEL    (0),
        .CLKC0_DUTY50           ("ENABLE"),
        .CLKC1_DUTY50           ("ENABLE"),
        .CLKC0_DUTY_INT         (5),
        .CLKC1_DUTY_INT         (1),

        .FRAC_ENABLE            ("ENABLE"),
        .SDM_FRAC               (HDMI_PLL_FRAC_0P1),
        .PLL_USR_RST            ("ENABLE"),
        .PLL_FASTLOOP           ("ENABLE"),
        .LPF_RES                (0),
        .LPF_CAP                (31),
        .ICP_CUR                (31),
        .REFCLK_DET_BYP         ("DISABLE"),
        .CLKC0_FRAC_EN          ("DISABLE"),
        .CLKC0_FRAC             (0),
        .PI_OUT_SEL             ("NORMAL"),
        .PI_FRAC_EN             ("DISABLE"),
        .CLKC0_PI_SHIFT_EN      ("DISABLE"),
        .PHASE_PATH_SEL         (0),
        .DYN_PHASE_PATH_SEL     ("DISABLE"),
        .DYN_FPHASE_EN          ("DISABLE"),
        .DYN_CPHASE_EN          ("DISABLE")
    ) u_hdmi_pll (
        .refclk      (refclk),
        .refclk_rst  (1'b0),
        // INTERNAL + VCO_PHASE0 selects the on-die VCO feedback, not fbclk.
        // Keep this unselected physical clock input on an existing clock net:
        // TD 6.2.1 failed to route its automatic constant clock-GND net.
        // This is NOT external feedback; do not change the PLL parameters.
        .fbclk       (refclk),
        .clkc        (clkc),
        .clkcb       (),
        .lock        (lock),
        .pllreset    (reset),
        .clkc_rst    (2'b00),
        .clkc_en     (7'b0000011),
        .wakeup      (1'b1),
        .cps_step    (1'b0),
        .pllpd       (1'b0),
        .drp_clk     (1'b0),
        .drp_rstn    (1'b1),
        .drp_sel     (1'b0),
        .drp_rd      (1'b0),
        .drp_wr      (1'b0),
        .drp_addr    (8'h00),
        .drp_wdata   (8'h00),
        .drp_err     (),
        .drp_rdy     (),
        .drp_rdata   (),
        .psclk       (1'b0),
        .psclksel    (3'b000),
        .psstep      (1'b0),
        .psdown      (1'b0),
        .psdone      (),
        .ssc_reset   (1'b0),
        .scan_clk    (1'b1),
        .scan_enable (1'b1),
        .scan_mode   (1'b0),
        .scan_resetn (1'b1)
    );

endmodule
